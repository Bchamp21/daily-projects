"""Day 16 DE: Genie space as code.

validate  - check genie_space.yml (3-part names, SELECT-only SQL, known tables)
comments  - emit COMMENT ON COLUMN SQL so Genie understands the columns
bench     - score Genie's answers (answers.json) against expected results locally
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sqlite3
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).parent
FORBIDDEN = re.compile(r"\b(insert|update|delete|merge|drop|alter|create|truncate|grant)\b", re.I)
TABLE_REF = re.compile(r"\b(?:from|join)\s+([\w.]+)", re.I)


def load(path: Path = HERE / "genie_space.yml") -> dict:
    return yaml.safe_load(Path(path).read_text())


def check_sql(sql: str, allowed: set[str]) -> list[str]:
    errs = []
    if not sql.strip().lower().startswith(("select", "with")):
        errs.append("must start with SELECT or WITH")
    if FORBIDDEN.search(sql):
        errs.append("contains a write/DDL keyword")
    for ref in TABLE_REF.findall(sql):
        if ref.lower() not in allowed:
            errs.append(f"unknown table {ref}")
    return errs


def validate(cfg: dict) -> list[str]:
    errors = []
    tables = cfg.get("tables") or []
    if not tables:
        errors.append("no tables listed")
    for t in tables:
        if t.count(".") != 2:
            errors.append(f"{t}: use catalog.schema.table")
    allowed = {t.lower() for t in tables}
    for t in cfg.get("column_docs", {}):
        if t.lower() not in allowed:
            errors.append(f"column_docs for unlisted table {t}")
    seen = set()
    for kind, key in (("sample_queries", "sql"), ("benchmarks", "expected_sql")):
        for i, item in enumerate(cfg.get(kind, [])):
            q = item.get("question", "").strip()
            if not q:
                errors.append(f"{kind}[{i}]: missing question")
            if kind == "sample_queries":
                if q.lower() in seen:
                    errors.append(f"duplicate sample question: {q}")
                seen.add(q.lower())
            errors += [f"{kind}[{i}] {q!r}: {e}" for e in check_sql(item.get(key, ""), allowed)]
    return errors


def comments_sql(cfg: dict) -> str:
    out = ["-- Generated by genie_check.py. Run in a Databricks SQL editor."]
    for table, cols in cfg.get("column_docs", {}).items():
        for col, text in cols.items():
            safe = text.replace("'", "''")
            out.append(f"ALTER TABLE {table} ALTER COLUMN {col} COMMENT '{safe}';")
    return "\n".join(out) + "\n"


# ---------- local Gold copy (SQLite) so benchmarks run without a workspace ----------
GOLD_SQL = """
CREATE TABLE gold_price_metrics AS
WITH w AS (
  SELECT ticker, trade_date, close,
    AVG(close) OVER (PARTITION BY ticker ORDER BY trade_date ROWS 2 PRECEDING) AS sma_3,
    MAX(close) OVER (PARTITION BY ticker ORDER BY trade_date) AS running_high
  FROM silver_prices)
SELECT ticker, trade_date, close, ROUND(sma_3, 4) AS sma_3,
       ROUND(close / running_high - 1, 6) AS drawdown
FROM w;
CREATE TABLE gold_ticker_summary AS
SELECT ticker, COUNT(*) AS trading_days,
  ROUND((SELECT close FROM gold_price_metrics b WHERE b.ticker=a.ticker ORDER BY trade_date DESC LIMIT 1) /
        (SELECT close FROM gold_price_metrics b WHERE b.ticker=a.ticker ORDER BY trade_date LIMIT 1) - 1, 6) AS period_return,
  MIN(drawdown) AS max_drawdown
FROM gold_price_metrics a GROUP BY ticker;
"""


def local_gold(csv_path: Path = HERE / "data" / "silver_prices_sample.csv") -> sqlite3.Connection:
    con = sqlite3.connect(":memory:")
    con.execute("CREATE TABLE silver_prices (ticker TEXT, trade_date TEXT, close REAL)")
    with open(csv_path) as f:
        rows = [(r["ticker"], r["trade_date"], float(r["close"])) for r in csv.DictReader(f)]
    con.executemany("INSERT INTO silver_prices VALUES (?,?,?)", rows)
    con.executescript(GOLD_SQL)
    return con


def to_local(sql: str) -> str:
    """market.gold.x -> x so the same SQL runs on SQLite."""
    return re.sub(r"\b\w+\.\w+\.(\w+)", r"\1", sql)


def result(con: sqlite3.Connection, sql: str) -> list[tuple]:
    rows = con.execute(to_local(sql)).fetchall()
    norm = [tuple(round(v, 4) if isinstance(v, float) else v for v in r) for r in rows]
    return sorted(norm, key=repr)


def bench(cfg: dict, answers: dict[str, str], con: sqlite3.Connection | None = None) -> dict:
    """Compare result sets, not SQL text: different SQL with the same answer passes."""
    con = con or local_gold()
    allowed = {t.lower() for t in cfg["tables"]}
    report = []
    for b in cfg.get("benchmarks", []):
        q = b["question"]
        got_sql = answers.get(q)
        if not got_sql:
            report.append({"question": q, "status": "missing"})
            continue
        errs = check_sql(got_sql, allowed)
        if errs:
            report.append({"question": q, "status": "unsafe", "why": errs})
            continue
        try:
            ok = result(con, got_sql) == result(con, b["expected_sql"])
        except sqlite3.Error as e:
            report.append({"question": q, "status": "error", "why": str(e)})
            continue
        report.append({"question": q, "status": "pass" if ok else "wrong"})
    passed = sum(r["status"] == "pass" for r in report)
    return {"passed": passed, "total": len(report), "score": passed / len(report) if report else 0.0, "results": report}


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--config", default=str(HERE / "genie_space.yml"))
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("validate")
    c = sub.add_parser("comments")
    c.add_argument("-o", "--out")
    b = sub.add_parser("bench")
    b.add_argument("--answers", required=True, help="JSON {question: sql} copied from Genie")
    b.add_argument("--min-score", type=float, default=0.8)
    a = p.parse_args(argv)
    cfg = load(Path(a.config))

    errors = validate(cfg)
    if errors:
        print("\n".join(f"ERROR {e}" for e in errors))
        return 2
    if a.cmd == "validate":
        print(f"OK: {len(cfg['tables'])} tables, {len(cfg.get('sample_queries', []))} samples, {len(cfg.get('benchmarks', []))} benchmarks")
        return 0
    if a.cmd == "comments":
        sql = comments_sql(cfg)
        Path(a.out).write_text(sql) if a.out else print(sql)
        return 0
    rep = bench(cfg, json.loads(Path(a.answers).read_text()))
    for r in rep["results"]:
        print(f"{r['status'].upper():8} {r['question']}")
    print(f"score {rep['passed']}/{rep['total']} = {rep['score']:.0%}")
    return 0 if rep["score"] >= a.min_score else 1


if __name__ == "__main__":
    sys.exit(main())
