CREATE CATALOG IF NOT EXISTS `market`;
ALTER CATALOG `market` OWNER TO `data_platform_admins`;
GRANT USE CATALOG ON CATALOG `market` TO `data_engineers`;
GRANT USE CATALOG ON CATALOG `market` TO `analysts`;
GRANT USE CATALOG ON CATALOG `market` TO `bi_readers`;
CREATE SCHEMA IF NOT EXISTS `market`.`bronze` COMMENT 'Raw ingest from on-prem Postgres market.prices';
GRANT USE SCHEMA, SELECT, MODIFY, CREATE TABLE ON SCHEMA `market`.`bronze` TO `data_engineers`;
CREATE SCHEMA IF NOT EXISTS `market`.`silver` COMMENT 'Cleaned, deduped daily prices';
GRANT USE SCHEMA, SELECT, MODIFY, CREATE TABLE ON SCHEMA `market`.`silver` TO `data_engineers`;
GRANT USE SCHEMA, SELECT ON SCHEMA `market`.`silver` TO `analysts`;
CREATE SCHEMA IF NOT EXISTS `market`.`gold` COMMENT 'Business-ready metrics for BI and Genie';
GRANT USE SCHEMA, SELECT, MODIFY, CREATE TABLE ON SCHEMA `market`.`gold` TO `data_engineers`;
GRANT USE SCHEMA, SELECT ON SCHEMA `market`.`gold` TO `analysts`;
GRANT USE SCHEMA, SELECT ON SCHEMA `market`.`gold` TO `bi_readers`;
ALTER TABLE `market`.`gold`.`gold_ticker_summary` SET TAGS ('domain' = 'markets', 'tier' = 'gold');
ALTER TABLE `market`.`silver`.`prices` SET TAGS ('domain' = 'markets', 'tier' = 'silver');
CREATE OR REPLACE FUNCTION `market`.`silver`.`mask_volume`(v BIGINT) RETURN CASE WHEN is_account_group_member('data_engineers') THEN v ELSE NULL END;
ALTER TABLE `market`.`silver`.`prices` ALTER COLUMN `volume` SET MASK `market`.`silver`.`mask_volume`;
CREATE OR REPLACE FUNCTION `market`.`silver`.`ticker_region_filter`(val STRING) RETURN (is_account_group_member('analysts_us') AND val IN ('AAPL', 'MSFT')) OR is_account_group_member('data_engineers');
ALTER TABLE `market`.`silver`.`prices` SET ROW FILTER `market`.`silver`.`ticker_region_filter` ON (`ticker`);
